async function computeServerExpectedCash(shift) {
  try {
    const key = shift.key;
    const dept = shift.dept;
    let cashTotal = 0;
    // Helper to get Lagos shift key for a date string/Date
    function lagosYMD(d) { try { return new Date(d).toLocaleDateString('sv-SE', { timeZone: 'Africa/Lagos' }); } catch (e) { return new Date(d).toISOString().slice(0,10); } }
    function lagosHour(d) { try { return parseInt(new Intl.DateTimeFormat('en-GB', { timeZone: 'Africa/Lagos', hour: '2-digit', hour12: false }).format(new Date(d)),10); } catch(e){ return new Date(d).getHours(); } }
    function shiftKeyFor(d) {
      const dt = new Date(d);
      const h = lagosHour(dt);
      let base = dt;
      // shiftStart from Config, default 9
      let shiftStart = 9;
      try { const cfg = global.__shiftStartHour; if (typeof cfg === 'number') shiftStart = cfg; } catch(e){}
      if (h < shiftStart) base = new Date(dt.getTime() - 86400000);
      return lagosYMD(base);
    }
    // Try to get shiftStart from Config if available
    let shiftStart = 9;
    try { const Config = require('../models/Config'); const cfg = await Config.findOne().sort({ createdAt: -1 }); if (cfg && typeof cfg.shiftStartHour === 'number') shiftStart = cfg.shiftStartHour; } catch(e){}
    global.__shiftStartHour = shiftStart;
    function isSameShift(dateStr) {
      if (!dateStr) return false;
      const d = new Date(dateStr.length===10 ? dateStr+'T12:00:00' : dateStr);
      return shiftKeyFor(d) === key;
    }

    if (dept === 'Restaurant' || dept === 'Pool Bar') {
      const deptFilter = dept === 'Restaurant' ? 'restaurant' : 'poolbar';
      const sales = await Sale.find({ department: deptFilter, status: 'completed' });
      for (const s of sales) {
        if (s.method !== 'Cash') continue;
        const d = s.createdAt ? lagosYMD(s.createdAt) : null;
        if (!d) continue;
        const sk = shiftKeyFor(s.createdAt);
        if (sk === key) cashTotal += Number(s.total) || 0;
      }
    } else if (dept === 'Front Desk' || dept === 'Rooms & Bookings' || dept === 'Rooms') {
      const bookings = await Booking.find({ guest: { $ne: '' } });
      for (const b of bookings) {
        const payments = b.payments || [];
        for (const p of payments) {
          if (p.mode !== 'Cash') continue;
          const pd = p.date || b.checkin;
          if (!isSameShift(pd)) continue;
          cashTotal += Number(p.amount) || 0;
        }
      }
    } else if (dept === 'Gym') {
      const members = await GymMember.find({});
      for (const m of members) {
        for (const p of (m.payments || [])) {
          if (p.mode !== 'Cash') continue;
          const pd = p.date || m.startDate;
          if (!isSameShift(pd)) continue;
          cashTotal += Number(p.amount) || 0;
        }
      }
    }
    return (Number(shift.openingFloat) || 0) + cashTotal;
  } catch (e) {
    console.error('[reconcile] computeServerExpectedCash failed', e.message);
    return null;
  }
}
exports.reconcileShift = asyncHandler(async (req, res) => {
  const { actualCash, notes, actor, type } = req.body;
  const actual = Number(actualCash) || 0;
  const shiftDoc = await Shift.findById(req.params.id);
  if (!shiftDoc) return res.status(404).json({ success: false, error: 'Shift not found' });
  let expected = await computeServerExpectedCash(shiftDoc);
  if (expected === null || isNaN(expected)) {
    // fallback to client value if server compute fails, but log
    expected = Number(req.body.expectedCash) || 0;
    console.warn('[reconcile] fallback to client expectedCash', expected);
  } else if (req.body.expectedCash !== undefined && Math.abs(Number(req.body.expectedCash) - expected) > 0.01) {
    console.warn(`[reconcile] client expectedCash ${req.body.expectedCash} != server ${expected} for shift ${shiftDoc.key}/${shiftDoc.dept}`);
  }
  const logEntry = {
    actor: actor || (req.user ? req.user.name : ''),
    actualCash: actual,
    expectedCash: expected,
    variance: actual - expected,
    notes: notes || '',
    type: type === 'correction' ? 'correction' : 'initial',
    date: new Date(),
  };
  const shift = await Shift.findByIdAndUpdate(
    req.params.id,
    {
      actualCash: actual, expectedCash: expected, variance: actual - expected,
      status: 'reconciled', notes: notes || '',
      $push: { reconciliationLog: logEntry },
    },
    { new: true, runValidators: true }
  );
  if (!shift) return res.status(404).json({ success: false, error: 'Shift not found' });
  res.json({ success: true, data: shift });
});

/* ── Procurement Finance Review — accountant sees/approves without entering procurement module ── */
function accountingActor(req) {
  return (req.user && (req.user.name || req.user.role)) || 'Accountant';
}
function isAccountantActor(req) {
  const role = String(req.user && req.user.role || '').toLowerCase();
  if (role === 'admin') return true;
  const privType = String(req.user && req.user.privileges && req.user.privileges.type || '').toLowerCase();
  return role === 'accountant' || privType === 'accountant';
}
function todayISO() { return new Date().toISOString().split('T')[0]; }

