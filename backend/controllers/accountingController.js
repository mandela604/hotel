exports.ledger = asyncHandler(async (req, res) => {
  const page = Math.max(1, parseInt(req.query.page, 10) || 1);
  const limit = Math.min(100, Math.max(1, parseInt(req.query.limit, 10) || 50));
  const from = req.query.from, to = req.query.to, type = req.query.type, dept = req.query.department;
  // Build from real sources
  const [roomRows, restRows, poolRows, gymRows, manualIncome, manualExpenses] = await Promise.all([
    aggregateRoomRevenue(from, to),
    aggregateOutletRevenue(from, to, 'restaurant', 'Restaurant'),
    aggregateOutletRevenue(from, to, 'poolbar', 'Pool Bar'),
    aggregateGymRevenue(from, to),
    IncomeEntry.find(from||to||dept||type ? {} : {}).lean(),
    ExpenseEntry.find(from||to ? {} : {}).lean(),
  ]);
  let entries = [];
  for (const r of [...roomRows, ...restRows, ...poolRows, ...gymRows]) {
    if (type && type !== 'income') continue;
    if (dept && r.department !== dept) continue;
    entries.push({ type: 'income', department: r.department, date: r.date, amount: r.amount, description: r.description, source: r.source });
  }
  for (const m of manualIncome) {
    if (type && type !== 'income') continue;
    if (dept && m.department !== dept) continue;
    if (from && m.date < from) continue;
    if (to && m.date > to) continue;
    entries.push({ type: 'income', department: m.department, date: fmtDate(m.date), amount: m.amount, description: m.description, source: 'manual' });
  }
  for (const e of manualExpenses) {
    if (type && type !== 'expense') continue;
    if (from && fmtDate(e.date) < from) continue;
    if (to && fmtDate(e.date) > to) continue;
    entries.push({ type: 'expense', department: e.category, date: fmtDate(e.date), amount: e.amount, description: e.description, source: 'manual' });
  }
  entries.sort((a,b)=> b.date.localeCompare(a.date));
  const total = entries.length;
  const paged = entries.slice((page-1)*limit, page*limit);
  res.json({ success: true, count: paged.length, total, page, pages: Math.ceil(total/limit)||1, data: paged });
});

